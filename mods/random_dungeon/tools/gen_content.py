def gen_sets(items):
    camp = open(os.path.join(MODS, 'empyrean_campaign/items/sets.txt'), encoding='utf8').read()
    ids = [int(x) for x in re.findall(r'^id=(\d+)', camp, re.M)] or [0]
    next_id = max(ids) + 1
    out = [HEADER, '# Copy of empyrean_campaign/items/sets.txt + Random Dungeon sets at the end.\n\n', camp.rstrip(), '\n']
    for group, (_, bl) in SET_BONUSES.items():
        members = [it['id'] for it in items if it['base'].startswith('items/base/armor/')
                   and (it['name'].startswith(group + ' ') or (group == 'Platemail' and it['name'] == 'Knight Helm'))
                   and not (group == 'Platemail' and it['name'].startswith('Blessed'))]
        if len(members) < 2:
            continue
        out.append('\n[set]\nid=%d\nname=%s Set\nitems=%s\ncolor=255,215,120\n' % (next_id, group, ','.join(members)))
        for count, stat, val in bl:
            out.append('bonus=%d,%s,%d\n' % (count, stat, val))
        next_id += 1
    write(rel('items/sets.txt'), ''.join(out))


# ------------------------------------------------------------------ loot
def gen_loot(items):
    """
    How Flare picks loot (LootManager::checkLoot): each "drop attempt" rolls ONE
    number 0-100; every entry whose chance >= roll is eligible, and the eligible
    entry with the SMALLEST chance wins (ties: random pick). So chances behave
    like nested rarity bands:
        P(unique) = unique, P(rare) = rare - unique, ... P(nothing) = 100 - gold
    Items outside the player's level window are skipped, so the roll falls to
    the next band. Enemies get `loot_count` attempts per death.
    """
    bands = list(csv.DictReader(open(os.path.join(DATA, 'loot_bands.csv'), encoding='utf8')))
    for b in bands:
        out = [HEADER, '# grade=%s  (see tools/ek_data/loot_bands.csv)\n' % b['grade']]
        out.append('\n[loot]\nid=currency\nchance=%s\nquantity=%s\nquantity_per_level=%s\n'
                   % (b['gold'], b['gold_qty'].replace('-', ','), b['gold_qty_per_level'].replace('-', ',')))
        for pid in ('2', '3'):  # health / mana potion
            out.append('\n[loot]\nid=%s\nchance=%s\nquantity=1\n' % (pid, b['potion']))
        for it in items:
            lvl = int(it['level'])
            lo = max(1, lvl - int(b['level_below']))
            hi = lvl + int(b['level_above'])
            out.append('\n[loot]\nid=%s\nchance=%s\nquantity=1\nrequires_level=%d,%d\n'
                       % (it['id'], b[it['band']], lo, hi))
        write(rel('loot/rd_drop_%s.txt' % b['grade']), ''.join(out))
    print('loot tables: %s' % ', '.join('rd_drop_%s' % b['grade'] for b in bands))
    return {b['grade']: b for b in bands}



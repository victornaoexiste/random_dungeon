def template_lines(name):
    if name in CUSTOM_TEMPLATES:
        return CUSTOM_TEMPLATES[name].splitlines()
    return open(os.path.join(MODS, 'empyrean_campaign/enemies/%s.txt' % name), encoding='utf8').read().splitlines()


def scale_line(line, hp_mult, dmg_mult):
    m = re.match(r'(stat|stat_per_level)=(hp|dmg_\w+),(\d+)$', line.strip())
    if not m:
        return line
    mult = hp_mult if m.group(2) == 'hp' else dmg_mult
    return '%s=%s,%d' % (m.group(1), m.group(2), max(1, int(round(int(m.group(3)) * mult))))



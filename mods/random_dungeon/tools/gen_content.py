def po_escape(s):
    return s.replace('\\', '\\\\').replace('"', '\\"')


def gen_po(items, enemies):
    pairs = [(it['name'], it['name_pt']) for it in items if it['name_pt']]
    pairs += [(e['name'], e['name_pt']) for e in enemies if e['name_pt']]
    pairs += [('%s Set' % g, 'Conjunto %s' % g) for g in SET_BONUSES]
    pairs += EXTRA_PT + EXTRA_PT_SLAYER
    import gen_skills
    pairs += gen_skills.translations()
    seen, body = set(), []
    for en, pt in pairs:
        if en in seen:
            continue
        seen.add(en)
        body.append('msgid "%s"\nmsgstr "%s"\n' % (po_escape(en), po_escape(pt)))
    head = ('# GENERATED by tools/gen_content.py -- edit name_pt in tools/ek_data/*.csv\n'
            'msgid ""\nmsgstr ""\n"Content-Type: text/plain; charset=UTF-8\\n"\n"Language: %s\\n"\n\n')
    for lang in ('pt_BR', 'pt'):
        write(rel('languages/data.%s.po' % lang), head % lang + '\n'.join(body))
    print('translations: %d names (pt_BR, pt)' % len(seen))



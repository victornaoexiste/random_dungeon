#!/usr/bin/env python3
"""
Random Dungeon content generator (items, loot, enemies, icons, translations).

Source of truth (edit these, then re-run this script):
  tools/ek_data/items.csv        one row per item (names, level, damage, bonuses, tint...)
  tools/ek_data/enemies.csv      one row per enemy variant (template, sprite, tint, strength)
  tools/ek_data/loot_bands.csv   drop chances per enemy grade  <-- "chance de loot"
  PALETTE below                  the color filters (tints) used by items and enemies

Everything this script writes is marked GENERATED at the top -- don't hand-edit
those files, edit the CSVs instead:
  items/items.txt, items/categories/rd_items.txt, items/sets.txt
  engine/icons.txt, images/icons/icons_rd.png
  animations/avatar/<body>/rd_*.txt      (tinted equipment layers)
  animations/enemies/rd/*.txt            (tinted enemy sprites)
  enemies/rd_*.txt, loot/rd_*.txt
  languages/data.pt_BR.po, languages/data.pt.po  (Portuguese names)
  ../ek_icons/images/icons/icons_rd.png  (optional mod with the original EK icons, see README)

Usage:  python3 tools/gen_content.py            (uses cached EK icons, downloads missing ones)
        python3 tools/gen_content.py --offline  (never touch the network)
"""

def gen_enemies(loot_grades):
    enemies = list(csv.DictReader(open(os.path.join(DATA, 'enemies.csv'), encoding='utf8')))
    in_il_common = 0
    for e in enemies:
        hp_mult, dmg_mult = float(e['hp_mult']), float(e['dmg_mult'])
        lvl = int(e['ek_level'])
        grade = e['grade']
        tier = next(t for cap, t in TIERS if lvl <= cap)
        family = 'rd_' + re.sub(r'\W+', '_', e['family'].lower()).strip('_')
        cats = [e['id'], tier, family, 'rd_all']
        # creature type, for item slayer bonuses (silver vs undead...). 'undead' is
        # also the campaign's own category for its skeletons and zombies.
        if FAMILY_TYPE.get(e['family']):
            cats.append(FAMILY_TYPE[e['family']])
        # open-world regions this enemy belongs to (tools/world/regions.csv): the
        # region's dungeons spawn from rd_reg_<region> / rd_regelite_<region>
        for reg in REGIONS:
            if e['id'] in reg['enemies'].split(';'):
                cats.append(('rd_regelite_' if grade == 'elite' else 'rd_reg_') + reg['id'])
        # per-zone dungeon category: region enemies within the zone's level band
        # (same rule as gen_world.zone_enemies, EK_BAND there)
        for zn in ZONES:
            if zn['dungeon'] and grade == 'normal' and e['id'] in REGION_BY_ID[zn['region']]['enemies'].split(';') \
                    and int(zn['level_min']) - 3 <= lvl <= int(zn['level_max']) + 2:
                cats.append('rd_dg_' + zn['id'])
        if grade == 'boss':
            cats.append('rd_boss')
        else:
            cats += ['rd_' + grade, 'il_common']   # il_common: also shows up in the procedural dungeon
            in_il_common += 1
        strength = (hp_mult + dmg_mult) / 2
        rarity = 'rare' if grade == 'boss' else ('uncommon' if grade == 'elite' or strength >= 1.35 else 'common')

        body = []
        for line in template_lines(e['template']):
            key = line.split('=', 1)[0].strip()
            if key in DROP_KEYS or key.startswith('#') or not line.strip():
                continue
            if key.endswith('_resist'):
                continue
            body.append(scale_line(line, hp_mult, dmg_mult))

        mod, anim = e['animation'].split(':')
        anim_path = 'animations/enemies/%s.txt' % anim
        if e['tint']:
            tinted_path = 'animations/enemies/rd/%s.txt' % e['id']
            write(rel(tinted_path), HEADER + color_mod_lines(e['tint']) + '\nINCLUDE %s\n' % anim_path)
            anim_path = tinted_path

        b = loot_grades.get(grade, loot_grades['normal'])
        out = [HEADER, '# %s (level %d, family %s)\n' % (e['name'], lvl, e['family'])]
        out.append('\n'.join(body) + '\n\n')
        out.append('name=%s\nlevel=1\ncategories=%s\nrarity=%s\n' % (e['name'], ','.join(cats), rarity))
        out.append('xp=%d\nxp_scaling=enemies/xp_scaling/il.txt\n' % max(1, round(2 * strength * XP_BASE)))
        out.append('animations=%s\n' % anim_path)
        for part in (e['resists'] or '').split(';'):
            if part:
                k, v = part.split(':')
                out.append('stat=%s,%s\n' % (k, v))
        # holy damage (tools/gen_skills.py): undead and demons are weak to it
        if FAMILY_TYPE.get(e['family']) in ('undead', 'demon'):
            out.append('stat=holy_resist,-50\n')
        if grade == 'boss' or any(r['boss'] == e['id'] for r in REGIONS):
            # world bosses stay dead until the hero visits a town (see gen_world.py)
            out.append('defeat_status=rd_boss_down_%s\n' % e['id'])
        out.append('loot=loot/rd_drop_%s.txt\nloot_count=%s,%s\n' % (grade if grade in loot_grades else 'normal',
                                                                     b['drops_min'], b['drops_max']))
        write(rel('enemies/%s.txt' % e['id']), ''.join(out))
    print('enemies: %d (%d also added to il_common for the procedural dungeon)' % (len(enemies), in_il_common))
    return enemies



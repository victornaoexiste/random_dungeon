# XP per kill = 2 * strength * XP_BASE, times the il table (x2 per enemy level).
# The campaign's own numbers (XP_BASE=1) need ~128 same-level kills per hero
# level; 5 makes it ~26. The infinite run adds engine/horde.txt xp_multiplier.
XP_BASE = 5
QUALITY = {'common': 'normal', 'uncommon': 'high', 'rare': 'epic', 'unique': 'unique'}


def rel(*p):
    return os.path.join(MOD, *p)


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf8') as f:
        f.write(text)


def locate(relpath):
    """Find a data file the way the engine would (our mod first, then base mods)."""
    for m in [os.path.basename(MOD)] + BASE_MODS:
        p = os.path.join(MODS, m, relpath)
        if os.path.exists(p):
            return p
    return None


def read_kv(relpath):
    """key=value pairs of a base file, following INCLUDEs (last value wins)."""
    out = {}
    p = locate(relpath)
    if not p:
        return out
    # fantasycore holds the full definition; empyrean may APPEND to it
    paths = [os.path.join(MODS, m, relpath) for m in reversed(BASE_MODS)]
    for p in paths:
        if not os.path.exists(p):
            continue
        for line in open(p, encoding='utf8'):
            line = line.strip()
            if line.startswith('INCLUDE '):
                out.update(read_kv(line.split(None, 1)[1]))
            elif '=' in line and not line.startswith('#'):
                k, v = line.split('=', 1)
                out[k] = v
    return out


def tint_rgb(name):
    c = PALETTE[name]
    return c[:3], (c[3] if len(c) > 3 else 255)


def color_mod_lines(name):
    rgb, a = tint_rgb(name)
    s = 'color_mod=%d,%d,%d\n' % rgb
    if a != 255:
        s += 'alpha_mod=%d\n' % a
    return s


def bonuses(s):
    out = []
    for part in (s or '').split(';'):
        if part.strip():
            k, v = part.split(':')
            out.append((k.strip(), v.strip()))
    return out


# ------------------------------------------------------------------ icons
_sheet = None


def flare_icon(idx):
    global _sheet
    if _sheet is None:
        _sheet = Image.open(os.path.join(MODS, 'fantasycore/images/icons/icons.png')).convert('RGBA')
    cols = _sheet.width // ICON
    x, y = (idx % cols) * ICON, (idx // cols) * ICON
    return _sheet.crop((x, y, x + ICON, y + ICON))


def tinted(img, name):
    if not name:
        return img
    rgb, _ = tint_rgb(name)
    r, g, b, a = img.split()
    r = r.point(lambda v: v * rgb[0] // 255)
    g = g.point(lambda v: v * rgb[1] // 255)
    b = b.point(lambda v: v * rgb[2] // 255)
    return Image.merge('RGBA', (r, g, b, a))


def ek_icon(url, offline):
    if not url:
        return None
    fn = os.path.join(EK_CACHE, url.rsplit('/', 1)[1])
    if not os.path.exists(fn):
        if offline:
            return None
        os.makedirs(EK_CACHE, exist_ok=True)
        req = urllib.request.Request('https://www.exiledkingdoms.com' + url, headers={'User-Agent': 'Mozilla/5.0'})
        try:
            data = urllib.request.urlopen(req, timeout=30).read()
        except Exception as e:
            print('  ! could not download %s: %s' % (url, e))
            return None
        open(fn, 'wb').write(data)
    im = Image.open(fn).convert('RGBA')
    if im.size != (ICON, ICON):
        # EK icons are 60 or 64 px: pad (don't blur) smaller ones, shrink bigger ones
        if im.width <= ICON and im.height <= ICON:
            canvas = Image.new('RGBA', (ICON, ICON), (0, 0, 0, 0))
            canvas.alpha_composite(im, ((ICON - im.width) // 2, (ICON - im.height) // 2))
            im = canvas
        else:
            im = im.resize((ICON, ICON), Image.LANCZOS)
    return im


# ------------------------------------------------------------------ items
def gen_items(offline):
    items = list(csv.DictReader(open(os.path.join(DATA, 'items.csv'), encoding='utf8')))
    cols = 8
    rows = (len(items) + cols - 1) // cols
    sheet = Image.new('RGBA', (cols * ICON, rows * ICON), (0, 0, 0, 0))
    ek_sheet = sheet.copy()
    out = [HEADER]
    avatar_tints = set()
    missing_ek = 0

    for n, it in enumerate(items):
        base = read_kv(it['base'])
        if not it['tint']:
            elems = [k[4:-4] for k, _ in bonuses(it['bonuses']) if k.startswith('dmg_') and k.endswith('_min')]
            if elems and elems[0] in ELEM_TINT:
                it = dict(it, tint=ELEM_TINT[elems[0]])
        icon_id = ICON_FIRST_ID + n
        pos = ((n % cols) * ICON, (n // cols) * ICON)
        flare = tinted(flare_icon(int(base.get('icon', 0))), it['tint'])
        sheet.alpha_composite(flare, pos)
        ek = ek_icon(it['ek_icon'], offline)
        if ek is None:
            missing_ek += 1
        if ek is not None and it.get('flavor') == 'extrapolated':
            ek = tinted(ek, it['tint'])  # borrowed icon (e.g. Bluesteel) recolored for the new material
        ek_sheet.alpha_composite(ek if ek is not None else flare, pos)

        out.append('\n[item]\nid=%s\nname=%s\n' % (it['id'], it['name']))
        if it.get('flavor') and it['flavor'] != 'extrapolated':
            out.append('flavor=%s\n' % it['flavor'])
        out.append('INCLUDE %s\n' % it['base'])
        out.append('level=%s\nquality=%s\nicon=%d\nprice=%s\n' % (it['level'], QUALITY[it['band']], icon_id, it['price']))
        out.append('requires_level=%s\n' % it['level'])
        if it['dmg_type']:
            out.append('dmg=%s,%s,%s\n' % (it['dmg_type'], it['dmg_min'], it['dmg_max']))
        if it['abs_min'] != '':
            out.append('abs=%s,%s\n' % (it['abs_min'], it['abs_max']))
        if it['two_handed'] == '1':
            out.append('disable_slots=off\n')
        # extra equip flags for the skills (tools/gen_skills.py): two-handed
        # weapons, staves and wands can be required by passive skills
        kind = it['base'].split('/')[-1][:-4]
        extra = (['two_handed'] if it['two_handed'] == '1' else []) + \
                (['staff'] if kind in ('staff', 'greatstaff') else []) + (['wand'] if kind in ('wand', 'rod') else [])
        if extra:
            flags = [f for f in base.get('equip_flags', '').split(',') if f]
            out.append('equip_flags=%s\n' % ','.join(flags + [f for f in extra if f not in flags]))
        for k, v in bonuses(it['bonuses']):
            out.append('bonus=%s,%s\n' % (k, v))
        if it.get('classes'):
            out.append('requires_class=%s\n' % it['classes'].replace(';', ','))
        for k, v in bonuses(it.get('slayer', '')):
            out.append('slayer=%s,%s\n' % (k, v))
        if it['tint'] and base.get('gfx'):
            gfx = 'rd_%s_%s' % (base['gfx'], it['tint'])
            out.append('gfx=%s\n' % gfx)
            avatar_tints.add((base['gfx'], it['tint']))
        if it['band'] == 'unique':
            out.append('loot_drops_max=1\n')

    write(rel('items/categories/rd_items.txt'), ''.join(out))
    os.makedirs(rel('images/icons'), exist_ok=True)
    sheet.save(rel('images/icons/icons_rd.png'))

    # optional EK-icon mod: same file path, so enabling the mod just swaps the art
    os.makedirs(os.path.join(EK_MOD, 'images/icons'), exist_ok=True)
    ek_sheet.save(os.path.join(EK_MOD, 'images/icons/icons_rd.png'))
    write(os.path.join(EK_MOD, 'settings.txt'),
          'description=Swaps Random Dungeon item icons for the original Exiled Kingdoms wiki icons. '
          'PERSONAL USE ONLY: this art belongs to Exiled Kingdoms, do not redistribute. Generated by '
          'random_dungeon/tools/gen_content.py.\nrequires=random_dungeon\ngame=flare-game\nversion=0.1\n'
          'engine_version_min=1.13.01\n')

    # tinted equipment layers on the hero (same sprite, color filter on top)
    for gfx, tint in sorted(avatar_tints):
        for body in BODIES:
            src = 'animations/avatar/%s/%s.txt' % (body, gfx)
            if locate(src):
                write(rel('animations/avatar/%s/rd_%s_%s.txt' % (body, gfx, tint)),
                      HEADER + color_mod_lines(tint) + '\nINCLUDE %s\n' % src)

    # items.txt: the engine loads ONE items.txt (highest mod wins), so repeat the campaign's list
    camp = open(os.path.join(MODS, 'empyrean_campaign/items/items.txt'), encoding='utf8').read()
    write(rel('items/items.txt'), HEADER + '# Copy of empyrean_campaign/items/items.txt + our items at the end.\n\n'
          + camp.rstrip() + '\n\n# Random Dungeon items (ids 5000+)\n'
          'INCLUDE items/categories/rd_items.txt\n')

    # icons.txt: same deal, one file wins
    write(rel('engine/icons.txt'), HEADER +
          'icon_set=0,images/icons/icons.png\nicon_set=256,images/icons/icons_empyrean.png\n'
          'icon_set=512,images/icons/icons_crafting.png\nicon_set=1024,images/icons/icons_overlay.png\n'
          'icon_set=%d,images/icons/icons_rd.png\n' % ICON_FIRST_ID +
          'icon_set=6144,images/icons/icons_skills.png\n')   # tools/gen_skills.py

    gen_sets(items)
    print('items: %d (icons: %d from EK, %d fallback to tinted Flare art), %d tinted equipment layers'
          % (len(items), len(items) - missing_ek, missing_ek, len(avatar_tints)))
    return items



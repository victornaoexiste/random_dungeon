# ------------------------------------------------------------------ tilesets
def gen_tilesets(force):
    for biome, b in BIOMES.items():
        src = os.path.join(MODS, 'fantasycore/tilesetdefs/tileset_%s.txt' % b['base'])
        text = open(src, encoding='utf8').read()
        if b['tint']:
            def repl(m):
                img = m.group(1)
                out = 'images/tilesets/rd_%s_%s' % (biome, os.path.basename(img))
                if force or not os.path.exists(rel(out)):
                    im = Image.open(os.path.join(MODS, 'fantasycore', img)).convert('RGBA')
                    r, g, bl, a = im.split()
                    t = b['tint']
                    im = Image.merge('RGBA', (r.point(lambda v: v * t[0] // 255), g.point(lambda v: v * t[1] // 255),
                                              bl.point(lambda v: v * t[2] // 255), a))
                    os.makedirs(os.path.dirname(rel(out)), exist_ok=True)
                    im.save(rel(out), optimize=True)
                    print('  tileset image %s' % out)
                return 'img=' + out
            text = re.sub(r'^img=(.*)$', repl, text, flags=re.M)
        write(rel('tilesetdefs/rd_%s.txt' % biome), HEADER + text)


# ------------------------------------------------------------------ zone terrain
def side_gap(side):
    """cells of the passage on a side (at the very edge)."""
    c0 = W // 2 - GAP // 2
    if side == 'n': return [(c0 + i, 0) for i in range(GAP)]
    if side == 's': return [(c0 + i, H - 1) for i in range(GAP)]
    if side == 'w': return [(0, c0 + i) for i in range(GAP)]
    return [(W - 1, c0 + i) for i in range(GAP)]


def arrival(side):
    """where you appear when entering through `side`."""
    c = W // 2
    return {'n': (c, BORDER + 1), 's': (c, H - BORDER - 2), 'w': (BORDER + 1, c), 'e': (W - BORDER - 2, c)}[side]


def blob_mask(rng, density, n_clusters, W=W, H=H):
    """clustered noise: mark cells near random cluster centres."""
    m = [[0.0] * W for _ in range(H)]
    for _ in range(n_clusters):
        cx, cy = rng.uniform(0, W), rng.uniform(0, H)
        r = rng.uniform(2.0, 6.5)
        for y in range(max(0, int(cy - r)), min(H, int(cy + r) + 1)):
            for x in range(max(0, int(cx - r)), min(W, int(cx + r) + 1)):
                d = math.hypot(x - cx, y - cy)
                if d < r:
                    m[y][x] += 1 - d / r
    vals = sorted(v for row in m for v in row)
    cut = vals[int(len(vals) * (1 - density))] if density > 0 else 99
    return [[m[y][x] > cut and m[y][x] > 0 for x in range(W)] for y in range(H)]


def carve(clear, x, y, r):
    for yy in range(y - r, y + r + 1):
        for xx in range(x - r, x + r + 1):
            if 0 <= xx < W and 0 <= yy < H:
                clear[yy][xx] = True


def carve_path(rng, clear, a, b, width=1):
    x, y = a
    while (x, y) != b:
        carve(clear, x, y, width)
        dx, dy = b[0] - x, b[1] - y
        if rng.random() < 0.3:  # wander a bit
            if rng.random() < 0.5 and dy: y += (1 if rng.random() < 0.5 else -1)
            elif dx: x += (1 if rng.random() < 0.5 else -1)
        elif abs(dx) > abs(dy) or (abs(dx) == abs(dy) and rng.random() < 0.5):
            x += (dx > 0) - (dx < 0)
        else:
            y += (dy > 0) - (dy < 0)
        x = min(max(x, 1), W - 2); y = min(max(y, 1), H - 2)
    carve(clear, x, y, width)


def pick(rng, weighted):
    total = sum(w for w, _, _ in weighted)
    r = rng.uniform(0, total)
    for w, ids, col in weighted:
        if r < w:
            return rng.choice(ids), col
        r -= w
    return rng.choice(weighted[-1][1]), weighted[-1][2]


def gen_zone(z, zones_by_pos, regions, dungeon):
    rng = random.Random(SEED_SALT + z['id'])
    region = regions[z['region']]
    b = BIOMES[region['biome']]
    col, row = int(z['col']), int(z['row'])
    lvl_min, lvl_max = int(z['level_min']), int(z['level_max'])
    town = z['town']

    bg = [[GROUND + (y % 4) * 4 + (x % 4) for x in range(W)] for y in range(H)]
    obj = [[0] * W for _ in range(H)]
    colm = [[0] * W for _ in range(H)]
    clear = [[False] * W for _ in range(H)]   # must stay walkable
    events, npcs, enemies = [], [], []
    center = (W // 2, H // 2)

    # passages to neighbours
    exits = {}
    for (dx, dy), side in SIDES.items():
        n = zones_by_pos.get((col + dx, row + dy))
        if n:
            exits[side] = n
    for side in exits:
        for (x, y) in side_gap(side):
            carve(clear, x, y, 0)
        gx, gy = side_gap(side)[GAP // 2]
        inner = {'n': (gx, BORDER + 1), 's': (gx, H - BORDER - 2), 'w': (BORDER + 1, gy), 'e': (W - BORDER - 2, gy)}[side]
        for (x, y) in side_gap(side):
            ix = x if side in 'ns' else inner[0]
            iy = y if side in 'we' else inner[1]
            carve_path(rng, clear, (x, y), (ix, iy), 0)
        carve_path(rng, clear, inner, center, 1)

    # town square / points of interest
    if town:
        carve(clear, center[0], center[1], 8)
    else:
        carve(clear, center[0], center[1], 2)
    spots = []   # clearings for enemies / camps
    for _ in range(40):
        if len(spots) >= 9:
            break
        x, y = rng.randint(BORDER + 4, W - BORDER - 5), rng.randint(BORDER + 4, H - BORDER - 5)
        if math.hypot(x - center[0], y - center[1]) < (14 if town else 7):
            continue
        if any(math.hypot(x - sx, y - sy) < 8 for sx, sy in spots):
            continue
        if any(math.hypot(x - ax, y - ay) < 7 for ax, ay in (arrival(s) for s in exits)):
            continue
        spots.append((x, y))
        carve(clear, x, y, 2)
        carve_path(rng, clear, (x, y), center, 0)

    # dungeon entrance: a cave mouth near a corner, reachable from the centre
    cave = None
    if dungeon:
        corner = rng.choice([(BORDER + 4, BORDER + 4), (W - BORDER - 5, BORDER + 4), (BORDER + 4, H - BORDER - 5), (W - BORDER - 5, H - BORDER - 5)])
        cave = corner
        carve(clear, cave[0], cave[1] + 1, 2)
        carve_path(rng, clear, (cave[0], cave[1] + 2), center, 1)

    # water pools (swamp, oasis...)
    for _ in range(b['water']):
        cx, cy = rng.randint(BORDER + 5, W - BORDER - 6), rng.randint(BORDER + 5, H - BORDER - 6)
        rw, rh = rng.randint(2, 4), rng.randint(2, 4)
        for y in range(cy - rh, cy + rh + 1):
            for x in range(cx - rw, cx + rw + 1):
                if not clear[y][x] and ((x - cx) / (rw + .5)) ** 2 + ((y - cy) / (rh + .5)) ** 2 <= 1:
                    bg[y][x] = WATER + (y % 4) * 4 + (x % 4)
                    colm[y][x] = 2

    # obstacle clusters
    mask = blob_mask(rng, b['density'], 30)
    for y in range(H):
        for x in range(W):
            edge = x < BORDER or y < BORDER or x >= W - BORDER or y >= H - BORDER
            if clear[y][x] or colm[y][x]:
                continue
            if edge:
                obj[y][x] = rng.choice(b['border']); colm[y][x] = 1
            elif (mask[y][x] and rng.random() < 0.7) or rng.random() < 0.015:
                t, c = pick(rng, b['obstacles']); obj[y][x] = t; colm[y][x] = c
            elif rng.random() < b['decor_rate']:
                obj[y][x] = rng.choice(b['decor'])
    # decor on paths too (walkable plants), but never on exits
    for y in range(BORDER, H - BORDER):
        for x in range(BORDER, W - BORDER):
            if clear[y][x] and not obj[y][x] and rng.random() < b['decor_rate'] / 3:
                obj[y][x] = rng.choice(b['decor'])

    def put(x, y, tile, c=2):
        obj[y][x] = tile; colm[y][x] = c

    # cave mouth + trigger in front of it
    if cave:
        x, y = cave
        put(x, y, CAVE, 1)
        for yy in (y + 1,):
            for xx in (x - 1, x, x + 1):
                obj[yy][xx] = 0; colm[yy][xx] = 0
        events.append('[event]\ntype=event\nlocation=%d,%d,3,1\nactivate=on_trigger\nhotspot=%d,%d,1,1\n'
                      'intermap=maps/world/dungeons/%s.txt\ntooltip=%s\n' % (x - 1, y + 1, x, y, z['id'], dungeon))
        # a new DUNGEON_VERSION regenerates this save's cached layout on the next visit
        events.append('[event]\ntype=event\n# dungeon version %d\nlocation=0,0,1,1\nactivate=on_load\n'
                      'requires_not_status=rd_dg_%s_v%d\nset_status=rd_dg_%s_f1_reset,rd_dg_%s_v%d\n'
                      % (DUNGEON_VERSION, z['id'], DUNGEON_VERSION, z['id'], z['id'], DUNGEON_VERSION))
        # where the dungeon's stairs drop you back (see gen_dungeon)
        events.append('[event]\ntype=event\n# back from the dungeon\nlocation=%d,%d,1,1\nintermap_id=rd_cave\n' % (x, y + 3))

    # town: campfire in the middle, tents and crates around, NPCs in a ring
    if town:
        cx, cy = center
        put(cx, cy, CAMP['fire'])
        for i, (dx, dy) in enumerate([(-5, -4), (5, -4), (-5, 4), (5, 4)]):
            put(cx + dx, cy + dy, CAMP['tent'])
            put(cx + dx + 1, cy + dy + 1, rng.choice(CAMP['crates']))
        ring = [(0, -3), (3, 0), (0, 3), (-3, 0), (2, 2), (-2, -2)]
        for (npc_id, *_), (dx, dy) in zip(TOWNS[town], ring):
            npcs.append('[npc]\ntype=npc\nlocation=%d,%d,1,1\nfilename=npcs/rd_%s.txt\n' % (cx + dx, cy + dy, npc_id))

    # enemy groups in the clearings. Towns are safe (no groups at all).
    # Elites (enemies.csv grade=elite) only show up in the highest-level zone of
    # their region, and even there at 1/ELITE_ODDS the weight of a normal enemy.
    cats = zone_enemies(z, [c for c in region['enemies'].split(';') if c])
    top_zone = z['id'] == REGION_TOP_ZONE.get(z['region'])
    weighted = []
    for c in cats:
        if ENEMY_GRADE.get(c) == 'elite':
            if top_zone:
                weighted.append(c)
        else:
            weighted += [c] * ELITE_ODDS
    boss_spot = None
    if z['boss'] and region['boss'] and spots:
        boss_spot = max(spots, key=lambda s: math.hypot(s[0] - center[0], s[1] - center[1]))
    for (x, y) in spots:
        if town:
            continue
        if (x, y) == boss_spot:
            enemies.append('[enemy]\ntype=enemy\n# boss (stays dead until the hero visits a town)\nlocation=%d,%d,1,1\ncategory=%s\nnumber=1\n'
                           'spawn_level=fixed,%d\nrequires_not_status=rd_boss_down_%s\n'
                           % (x, y, region['boss'], lvl_max + 1, region['boss']))
            continue
        foe = rng.choice(weighted)
        # at its own level (+-1), kept inside the zone's range
        lvl = max(lvl_min, min(lvl_max, ENEMY_EK.get(foe, lvl_min) + rng.randint(-1, 1)))
        enemies.append('[enemy]\ntype=enemy\nlocation=%d,%d,3,3\ncategory=%s\nnumber=%s\nspawn_level=fixed,%d\n'
                       % (x - 1, y - 1, foe, rng.choice(['1,2', '2,3', '2,4']), lvl))
        if region['biome'] == 'badlands' and rng.random() < 0.5:   # orc war camps
            put(x + 2, y - 2, CAMP['tent']); put(x - 2, y + 2, CAMP['fire'])

    # passages
    for side, n in exits.items():
        cells = side_gap(side)
        xs = [c[0] for c in cells]; ys = [c[1] for c in cells]
        ax, ay = arrival(OPPOSITE[side])
        events.append('[event]\ntype=event\n# to %s\nlocation=%d,%d,%d,%d\nactivate=on_trigger\nhotspot=location\n'
                      'intermap=maps/world/%s.txt,%d,%d\ntooltip=%s\n'
                      % (n['id'], min(xs), min(ys), max(xs) - min(xs) + 1, max(ys) - min(ys) + 1, n['id'], ax, ay, n['name']))

    if town:
        # resting in a town brings every world boss back (EK respawns them on a timer)
        bosses = sorted(set(r['boss'] for r in REGIONS_ALL.values() if r['boss']))
        events.append('[event]\ntype=event\n# bosses respawn\nlocation=1,0,1,1\nactivate=on_load\nunset_status=%s\n'
                      % ','.join('rd_boss_down_%s' % b for b in bosses))
    hero = (center[0] + 1, center[1] + 2) if town else arrival(next(iter(exits))) if exits else center
    title = '%s — %s' % (z['name'], region['name']) if z['name'] != region['name'] else z['name']

    def layer(name, grid):
        return '[layer]\ntype=%s\ndata=\n%s\n\n' % (name, ',\n'.join(','.join(str(v) for v in r) for r in grid))

    out = [HEADER, '# %s | região: %s (%s) | bioma: %s | nível %d-%d\n\n'
           % (z['name'], region['name'], region['people'], region['biome'], lvl_min, lvl_max)]
    out.append('[header]\nwidth=%d\nheight=%d\ntilewidth=192\ntileheight=96\norientation=isometric\n'
               'background_color=0,0,0,255\nhero_pos=%d,%d\nmusic=music/%s.ogg\ntileset=tilesetdefs/rd_%s.txt\ntitle=%s\n\n'
               % (W, H, hero[0], hero[1], region['music'], region['biome'], title))
    out.append(layer('background', bg))
    out.append(layer('object', obj))
    out.append(layer('collision', colm))
    out.append('\n'.join(events) + '\n' + '\n'.join(npcs) + '\n' + '\n'.join(enemies))
    write(rel('maps/world/%s.txt' % z['id']), ''.join(out))
    return len(enemies)


# ------------------------------------------------------------------ mode maps
# Infinite run: one open arena per biome; maps/run/start.txt sends each new run
# to a random one (HordeManager is active on everything under maps/run/, see
# engine/horde.txt). Test room: maps/dev_room.txt, where the dev kit button shows.
RUN_BIOMES = ['meadow', 'desert', 'badlands', 'glacier', 'swamp', 'volcanic', 'arcane', 'ashen']
ARENA = 80
DEV = 30


def open_map(map_id, biome, size, density, title, music, events, seed, hero=None, npcs=()):
    rng = random.Random(SEED_SALT + seed)
    b = BIOMES[biome]
    bg = [[GROUND + (y % 4) * 4 + (x % 4) for x in range(size)] for y in range(size)]
    obj = [[0] * size for _ in range(size)]
    colm = [[0] * size for _ in range(size)]
    c = size // 2
    mask = blob_mask(rng, density, size // 3, size, size)
    for y in range(size):
        for x in range(size):
            if x < BORDER or y < BORDER or x >= size - BORDER or y >= size - BORDER:
                obj[y][x] = rng.choice(b['border']); colm[y][x] = 1
            elif math.hypot(x - c, y - c) < 6:
                continue
            elif mask[y][x] and rng.random() < 0.6:
                t, cc = pick(rng, b['obstacles']); obj[y][x] = t; colm[y][x] = cc
            elif rng.random() < b['decor_rate']:
                obj[y][x] = rng.choice(b['decor'])
    for ev in events:  # keep event cells walkable
        x, y = ev[0], ev[1]
        for yy in range(y - 1, y + 2):
            for xx in range(x - 1, x + 2):
                obj[yy][xx] = 0; colm[yy][xx] = 0
    hero = hero or (c, c)

    def layer(name, grid):
        return '[layer]\ntype=%s\ndata=\n%s\n\n' % (name, ',\n'.join(','.join(str(v) for v in r) for r in grid))
    out = [HEADER, '[header]\nwidth=%d\nheight=%d\ntilewidth=192\ntileheight=96\norientation=isometric\n'
           'background_color=0,0,0,255\nhero_pos=%d,%d\nmusic=music/%s.ogg\ntileset=tilesetdefs/rd_%s.txt\ntitle=%s\n\n'
           % (size, size, hero[0], hero[1], music, biome, title)]
    out += [layer('background', bg), layer('object', obj), layer('collision', colm)]
    for ev in events:
        x, y, target, tooltip = ev[:4]
        size = ev[4] if len(ev) > 4 else 1   # square area centred on x,y (around a prop that blocks its own tile)
        # "book:rd:sanctuary" opens a menu (GameStatePlay turns that book into the Sanctuary)
        action = ('book=%s' % target[5:]) if target.startswith('book:') else ('intermap=%s' % target)
        out.append('[event]\ntype=event\nlocation=%d,%d,%d,%d\nactivate=on_trigger\nhotspot=location\n'
                   '%s\ntooltip=%s\n\n' % (x - size // 2, y - size // 2, size, size, action, tooltip))
    for x, y, npc in npcs:
        out.append('[npc]\ntype=npc\nlocation=%d,%d,1,1\nfilename=npcs/rd_%s.txt\n\n' % (x, y, npc))
    write(rel(map_id), ''.join(out))



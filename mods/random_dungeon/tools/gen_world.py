    ev = []
    for i, biome in enumerate(RUN_BIOMES):
        ev.append('[event]\ntype=event\nlocation=0,0,1,1\nactivate=on_load\nchance_exec=%.2f\n'
                  'intermap=maps/run/arena_%s.txt\n' % (100.0 / (len(RUN_BIOMES) - i), biome))

IL = 'empyrean_campaign/maps/iron_labyrinth/'
# Bump when the dungeon rooms change: every save regenerates its cached
# dungeon layouts on the next visit (the engine caches procgen maps per save).
DUNGEON_VERSION = 3
IL_SCRIPTS = 'empyrean_campaign/scripts/maps/iron_labyrinth/'


def dungeon_chunk(text, z, region):
    """Adapt one Iron Labyrinth room chunk to this zone's dungeon."""
    prefix = 'rd_dg_%s_' % z['id']
    level = int(z['level_max']) + 1
    t = text.replace('emp_il_', prefix)                      # own door/chest/room statuses
    t = re.sub(r'category=il_\w+', 'category=rd_dg_%s' % z['id'], t)   # region monsters of this zone's level band
    t = re.sub(r'spawn_level=hero_level,[\d.]+', 'spawn_level=fixed,%d' % level, t)
    t = t.replace('loot=loot/il_chest_common.txt', 'loot=loot/rd_drop_elite.txt')
    t = t.replace('filename=npcs/il_loren.txt', 'filename=npcs/rd_dungeon_trader.txt')
    t = re.sub(r'script=scripts/maps/iron_labyrinth/(f1_key_chest_\d)\.txt',
               lambda m: 'script=scripts/world/%s_%s.txt' % (z['id'], m.group(1)), t)
    # campaign story notes and the warp room teleporter don't exist here
    t = re.sub(r'\nscript=scripts/maps/iron_labyrinth/(notes_drop\w*|warp_tele)\.txt', '', t)
    return t


def gen_dungeon(z, region):
    """
    One procedural dungeon per zone with a `dungeon` column: the Iron Labyrinth
    room chunks, copied and adapted (region monsters at a fixed level, own
    door/chest statuses, our loot). Entering sets the floor status the rooms
    need for their doors and key chests. The layout is generated once per save
    and then cached by the engine, like a fixed EK dungeon.
    """
    zid = z['id']
    prefix = 'rd_dg_%s_' % zid
    folder = 'maps/world/dungeons/%s' % zid
    rules = open(os.path.join(MODS, 'empyrean_campaign/maps/procgen_rules/iron_labyrinth.txt'), encoding='utf8').read()
    chunks = re.findall(r'^filename=maps/iron_labyrinth/(\S+)$', rules, re.M)
    out_chunks = []
    for c in chunks:
        text = open(os.path.join(MODS, IL, c), encoding='utf8').read()
        write(rel('%s/%s' % (folder, c.replace('/', '_'))), HEADER + dungeon_chunk(text, z, region))
        out_chunks.append('%s/%s' % (folder, c.replace('/', '_')))

    # start room: stairs back up to the cave, floor status on load
    start = dungeon_chunk(open(os.path.join(MODS, IL, 'f1/start.txt'), encoding='utf8').read(), z, region)
    events = start.split('\n[event]')
    keep = [events[0]]
    for e in events[1:]:
        if 'Stairs Up' in e:
            e = re.sub(r'intermap=.*', 'intermap=maps/world/%s.txt,-1,-1,rd_cave' % zid, e)
            e = re.sub(r'tooltip=.*', 'tooltip=%s' % z['name'], e)
            keep.append(e)
        elif 'Spawn point' in e or 'Reset Floor' in e:
            keep.append(e)
    keep.append('\n# floor status the rooms need (doors, key chests)\ntype=event\nlocation=2,0,1,1\nactivate=on_load\nset_status=%sf1\n' % prefix)
    write(rel('%s/start.txt' % folder), HEADER + '\n[event]'.join(keep))

    # end room: the stairs down become the way out, guarded by the region's elite
    end = dungeon_chunk(open(os.path.join(MODS, IL, 'f1/end.txt'), encoding='utf8').read(), z, region)
    end = re.sub(r'intermap=maps/iron_labyrinth_f2\.txt', 'intermap=maps/world/%s.txt,-1,-1,rd_cave' % zid, end)
    end = re.sub(r'tooltip=Iron Labyrinth: Level 2', 'tooltip=%s' % z['name'], end)
    end = re.sub(r'\nset_status=%sf2' % prefix, '', end)
    elite = [c for c in region['enemies'].split(';') if ENEMY_GRADE.get(c) == 'elite']
    guard = 'rd_regelite_%s' % region['id'] if elite else 'rd_reg_%s' % region['id']
    end += ('\n[enemy]\ntype=enemy\n# guardian of the way out\nlocation=10,8,8,3\ncategory=%s\nnumber=1\nspawn_level=fixed,%d\n'
            % (guard, int(z['level_max']) + 2))
    write(rel('%s/end.txt' % folder), HEADER + end)

    # key-chest scripts with this dungeon's statuses and our loot
    for n in (1, 2):
        sc = open(os.path.join(MODS, IL_SCRIPTS, 'f1_key_chest_%d.txt' % n), encoding='utf8').read()
        sc = sc.replace('emp_il_', prefix).replace('loot=loot/il_chest_common.txt', 'loot=loot/rd_drop_elite.txt')
        write(rel('scripts/world/%s_f1_key_chest_%d.txt' % (zid, n)), HEADER + sc)

    settings = open(rel('maps/procgen_rules/random_dungeon.txt'), encoding='utf8').read()
    settings = settings[settings.index('[settings]'):settings.index('[chunks]')]
    write(rel('maps/procgen_rules/rd_world_%s.txt' % zid), HEADER + settings + '[chunks]\nfilename=%s/start.txt\nfilename=%s/end.txt\n'
          % (folder, folder) + ''.join('filename=%s\n' % c for c in out_chunks if not c.endswith(('f1_start.txt', 'f1_end.txt'))))
    d = open(rel('maps/dungeon.txt'), encoding='utf8').read()
    d = d.replace('maps/procgen_rules/random_dungeon.txt', 'maps/procgen_rules/rd_world_%s.txt' % zid)
    d = re.sub(r'title=.*', 'title=%s' % z['dungeon'], d)
    d = re.sub(r'music=.*', 'music=music/dungeon_theme.ogg', d)
    d = d.replace('[header]\n', '[header]\nprocgen_reset_status=%sf1_reset\n' % prefix, 1)
    write(rel('maps/world/dungeons/%s.txt' % zid), HEADER + d)
    # the old single-file start room from the first version
    old = rel('maps/world/dungeons/%s_start.txt' % zid)
    if os.path.exists(old):
        os.remove(old)



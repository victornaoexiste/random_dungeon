EK_BAND = (-3, 2)


def zone_enemies(z, cats):
    lo, hi = int(z['level_min']) + EK_BAND[0], int(z['level_max']) + EK_BAND[1]
    fit = [c for c in cats if lo <= ENEMY_EK.get(c, 0) <= hi]
    if fit:
        return fit
    # nothing in range: the closest ones
    near = min(abs(ENEMY_EK.get(c, 0) - int(z['level_min'])) for c in cats)
    return [c for c in cats if abs(ENEMY_EK.get(c, 0) - int(z['level_min'])) == near]

#!/usr/bin/env python3
"""
Random Dungeon skills: the Exiled Kingdoms skill system with our own names.

  python3 tools/gen_skills.py

Reads tools/ek_data/skills.csv (names, tab, classes, ranks, point cost per
rank, requirements) and the mechanics table below (SPEC: what every rank
does), and writes:

  powers/skills.txt              one power per skill rank (ids 6000+)
  powers/effects.txt             APPENDed effects (Duelist stacks)
  engine/damage_types.txt        APPENDed poison and holy damage
  powers/trees/rd_<class>.txt    the skills sheet of each class: tabs
                                 Class / General / Advanced (EK layout)
  enemies/rd_summon_*.txt        allies the summoning skills call
  images/icons/icons_skills.png  skill icons (tinted Flare icons, 6144+)

Translations (names and every rank's description) are returned by
translations() and written by gen_content.py into languages/data.pt*.po.

EK -> Random Dungeon scale: flat damage x2, mana x3, armor ~ absorb / 2,
healing x4, traits -> primary stats (see ek_data/make_skills_csv.py).
Things that don't exist in a run (towns, rumours, traps to disarm, days)
became co-op friendly equivalents (see the notes in SPEC).
"""

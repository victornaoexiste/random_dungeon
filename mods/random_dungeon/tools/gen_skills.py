GRID_X, GRID_Y, COLS, DX, DY = 96, 122, 5, 96, 84   # matches darkfantasy_gui gen_theme panel_powers()


def gen_trees(skills):
    by_id = {s['id']: s for s in skills}
    for cls in CLASSES:
        lines = [HEADER, '# %s skills sheet (menus/powers.txt detail_area = EK layout)\n' % cls.capitalize()]
        for _k, title in TABS:
            lines += ['[tab]', 'title=%s' % title, '']
        for t, (tab, _title) in enumerate(TABS):
            mine = [s for s in skills if s['tab'] == tab and (cls in s['classes'].split(',') or s['classes'] == 'all')]
            for n, s in enumerate(mine):
                x, y = GRID_X + (n % COLS) * DX, GRID_Y + (n // COLS) * DY
                lines += ['[power]', 'id=%d' % pid(s, 0), 'tab=%d' % t, 'position=%d,%d' % (x, y),
                          'requires_point=%d' % s['costs'][0]]
                if s['requires_level']:
                    lines.append('requires_level=%s' % s['requires_level'])
                for req in filter(None, s['requires'].split(';')):
                    parts = req.split(':')
                    if parts[0] == 'skill':
                        other = by_id[parts[1]]
                        if cls in other['classes'].split(',') or other['classes'] == 'all':
                            lines.append('requires_power=%d' % pid(other, int(parts[2]) - 1))
                    else:
                        lines.append('requires_primary=%s,%s' % (parts[0], parts[1]))
                if s['ranks'] > 1:
                    lines.append('upgrades=%s' % ','.join(str(pid(s, r)) for r in range(1, s['ranks'])))
                lines.append('')
                for r in range(1, s['ranks']):
                    lines += ['[upgrade]', 'id=%d' % pid(s, r), 'requires_point=%d' % s['costs'][r], '']
        write(rel('powers', 'trees', 'rd_%s.txt' % cls), '\n'.join(lines))


def gen_icons(skills):
    from PIL import Image
    src = Image.open(os.path.join(MODS, 'fantasycore', 'images', 'icons', 'icons.png')).convert('RGBA')
    S = 64
    cols = 8
    sheet = Image.new('RGBA', (cols * S, ((len(skills) + cols - 1) // cols) * S), (0, 0, 0, 0))
    for s in skills:
        idx, tint = ICON[s['id']]
        ic = src.crop(((idx % 8) * S, (idx // 8) * S, (idx % 8) * S + S, (idx // 8) * S + S))
        if tint:
            r, g, b, a = ic.split()
            r = r.point(lambda v, k=tint[0]: v * k // 255)
            g = g.point(lambda v, k=tint[1]: v * k // 255)
            b = b.point(lambda v, k=tint[2]: v * k // 255)
            ic = Image.merge('RGBA', (r, g, b, a))
        i = s['index']
        sheet.alpha_composite(ic, ((i % cols) * S, (i // cols) * S))
    out = rel('images', 'icons', 'icons_skills.png')
    os.makedirs(os.path.dirname(out), exist_ok=True)
    sheet.save(out)



def build(skills):
    """Rank objects for every skill; checks SPEC covers skills.csv"""
    missing = [s['id'] for s in skills if s['id'] not in SPEC]
    if missing:
        sys.exit('gen_skills: no SPEC for %s' % ', '.join(missing))
    out = {}
    for s in skills:
        out[s['id']] = [SPEC[s['id']](r) for r in range(s['ranks'])]
    return out


def gen_powers(skills, ranks):
    body = [HEADER, '# %d skills, ids %d-%d (skill index * 5 + rank)\n' % (len(skills), ID_BASE, ID_BASE + len(skills) * 5)]
    for s in skills:
        body.append('\n# ---- %s (%s, %s; EK: %s)' % (s['name'], s['tab'], s['classes'], s['ek_name']))
        for r, rk in enumerate(ranks[s['id']]):
            body.append('[power]\nid=%d\nname=%s\ndescription=%s\nicon=%d' % (pid(s, r), s['name'], rk.en, ICON_BASE + s['index']))
            body += rk.lines
            body.append('')
    # the classes' basic attacks trigger "on_active_power" passives
    # (Wide Swing, Duelist); a second [power] section only adds this key
    body.append('\n# basic attacks: Swing, Blood Strike, Shoot, Dagger Strike, Holy Strike, Channel, Mage basic')
    for basic in BASIC_ATTACKS:
        body.append('[power]\nid=%d\ncan_trigger_passives=true\n' % basic)
    write(rel('powers', 'skills.txt'), '\n'.join(body))


